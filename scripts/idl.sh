#!/usr/bin/env bash
# Rebuilds the IDL and its TypeScript type from the program and copies both into a checkout
# of the SDK (github.com/aequa-finance/aequa-sdk), where the IDL is also written as a module,
# idl.ts, so the SDK loads it without a JSON import. Needs the Anchor CLI 1.2.1 on PATH.
#
#   scripts/idl.sh <path to aequa-sdk>
set -euo pipefail
sdk="$(cd "${1:?path to an aequa-sdk checkout}" && pwd)"
cd "$(dirname "$0")/.."
mkdir -p target/idl target/types
anchor idl build -p aequa -o target/idl/aequa.json
anchor idl type target/idl/aequa.json -o target/types/aequa.ts
cp target/idl/aequa.json target/types/aequa.ts "$sdk/src/idl/"
{ echo "// Generated by aequa's scripts/idl.sh from target/idl/aequa.json."; printf 'const idl: object = '; cat target/idl/aequa.json; echo ';'; echo 'export default idl;'; } > "$sdk/src/idl/idl.ts"
echo "IDL copied to $sdk/src/idl"
